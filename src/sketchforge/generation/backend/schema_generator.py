def generate_test_py(spec: AppSpec) -> str:
    lines: list[str] = [
        '"""Automated tests for backend models — generated by SketchForge."""',
        "from __future__ import annotations",
        "",
        "import pytest",
        "import tempfile",
        "from pathlib import Path",
        "",
        "import sys",
        "sys.path.insert(0, str(Path(__file__).parents[2]))",
        "",
        "from backend.database import initialise, connect",
        "from backend.models import " + ", ".join(e.name for e in spec.entities),
        "from backend import logic",
        "",
        "",
        "@pytest.fixture(autouse=True)",
        "def tmp_db(tmp_path, monkeypatch):",
        '    """Each test gets an isolated in-memory database."""',
        "    db = tmp_path / 'test.db'",
        "    import backend.database as db_mod",
        "    monkeypatch.setattr(db_mod, 'DB_PATH', db)",
        "    initialise(db)",
        "    yield db",
        "",
        "",
    ]
    for entity in spec.entities:
        lines.extend(_test_crud(entity))
        lines.append("")
    return "\n".join(lines)


def _test_crud(entity: EntitySpec) -> list[str]:
    table = _snake(entity.name)
    pk = entity.primary_key
    sample_kwargs = ", ".join(
        f'{f.name}="test_{f.name}"' if _py_type(f.type) == "str" else f"{f.name}=0.0"
        for f in entity.fields
    )
    return [
        f"def test_{table}_crud():",
        f'    """Create, read, update, delete for {entity.name}."""',
        f"    obj = {entity.name}({sample_kwargs})",
        f"    created = logic.create_{table}(obj)",
        f"    assert created.{pk} is not None",
        "",
        f"    fetched = logic.get_{table}(created.{pk})",
        f"    assert fetched is not None",
        f"    assert fetched.{entity.fields[0].name if entity.fields else pk} == created.{entity.fields[0].name if entity.fields else pk}",
        "",
        f"    all_items = logic.list_{table}()",
        f"    assert len(all_items) == 1",
        "",
        f"    deleted = logic.delete_{table}(created.{pk})",
        f"    assert deleted",
        f"    assert logic.get_{table}(created.{pk}) is None",
    ]


# ---------------------------------------------------------------------------
# helpers
# ---------------------------------------------------------------------------

def _snake(s: str) -> str:
    import re
    s = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", s)
    s = re.sub(r"([a-z\d])([A-Z])", r"\1_\2", s)
    return s.lower().replace(" ", "_")
