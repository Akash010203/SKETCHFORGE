def generate_database_py(spec: AppSpec) -> str:
    schema_path = "backend/schema.sql"
    return f'''\
"""Database initialisation — generated by SketchForge."""
from __future__ import annotations

import sqlite3
from pathlib import Path

DB_PATH = Path("data/{_snake(spec.name)}.db")
SCHEMA = Path("{schema_path}")


def connect(db_path: Path = DB_PATH) -> sqlite3.Connection:
    """Return a sqlite3 connection with row factory and FK enforcement."""
    db_path.parent.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(str(db_path))
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA journal_mode=WAL")
    conn.execute("PRAGMA foreign_keys=ON")
    return conn


def initialise(db_path: Path = DB_PATH, schema: Path = SCHEMA) -> None:
    """Create tables if they don\'t exist."""
    conn = connect(db_path)
    sql = schema.read_text(encoding="utf-8")
    conn.executescript(sql)
    conn.commit()
    conn.close()


if __name__ == "__main__":
    initialise()
    print(f"Database ready at {{DB_PATH}}")
'''


