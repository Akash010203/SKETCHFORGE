"""Backend code generator: produces SQLite schema, data models, CRUD logic, and tests.

Invoked from project_export.py via render_backend_file().
"""
from __future__ import annotations

from sketchforge.generation.app_specification import AppSpec, EntitySpec, FieldSpec
from sketchforge.generation.project_planner import PlannedFile, ProjectPlan


def render_backend_file(pf: PlannedFile, plan: ProjectPlan) -> str:
    """Dispatch to the appropriate backend code generator."""
    g = pf.generator
    spec = plan.spec
    if g == "backend_schema":
        return generate_schema_sql(spec)
    if g == "backend_models":
        return generate_models_py(spec)
    if g == "backend_db":
        return generate_database_py(spec)
    if g == "backend_logic":
        return generate_logic_py(spec)
    if g == "backend_test":
        return generate_test_py(spec)
    return f"# {pf.relative_path} — generated by SketchForge\n"


# ---------------------------------------------------------------------------
# SQL Schema
# ---------------------------------------------------------------------------

def generate_schema_sql(spec: AppSpec) -> str:
    lines: list[str] = [
        "-- Generated by SketchForge",
        "-- SQLite schema for " + spec.name,
        "",
        "PRAGMA journal_mode=WAL;",
        "PRAGMA foreign_keys=ON;",
        "",
    ]
    for entity in spec.entities:
        lines.extend(_table_ddl(entity))
        lines.append("")
    return "\n".join(lines)


def _table_ddl(entity: EntitySpec) -> list[str]:
    table = _snake(entity.name)
    lines = [f"CREATE TABLE IF NOT EXISTS {table} ("]
    cols = [f"  {entity.primary_key} INTEGER PRIMARY KEY AUTOINCREMENT"]
    for field in entity.fields:
        col_type = _sql_type(field.type)
        nullable = "" if field.required else " NOT NULL" if False else ""
        cols.append(f"  {field.name} {col_type}{nullable}")
    if entity.timestamps:
        cols.append("  created_at TEXT DEFAULT (datetime('now'))")
        cols.append("  updated_at TEXT DEFAULT (datetime('now'))")
    lines.append(",\n".join(cols))
    lines.append(");")
    lines.append("")
    lines.append(
        f"CREATE TRIGGER IF NOT EXISTS update_{table}_updated_at"
    )
    lines.append(f"  AFTER UPDATE ON {table}")
    lines.append(f"  FOR EACH ROW")
    lines.append(
        f"  BEGIN UPDATE {table} SET updated_at = datetime('now') WHERE {entity.primary_key} = NEW.{entity.primary_key}; END;"
    )
    return lines


def _sql_type(field_type: str) -> str:
    return {
        "text": "TEXT",
        "email": "TEXT",
        "password": "TEXT",
        "number": "REAL",
        "select": "TEXT",
    }.get(field_type, "TEXT")


# ---------------------------------------------------------------------------
# Python Models (dataclasses + sqlite3 helper)
# ---------------------------------------------------------------------------

def generate_models_py(spec: AppSpec) -> str:
    lines: list[str] = [
        '"""Data models — generated by SketchForge."""',
        "from __future__ import annotations",
        "",
        "from dataclasses import dataclass, field",
        "from typing import Optional",
        "",
    ]
    for entity in spec.entities:
        lines.extend(_dataclass(entity))
        lines.append("")
    return "\n".join(lines)


def _dataclass(entity: EntitySpec) -> list[str]:
    lines = ["@dataclass"]
    lines.append(f"class {entity.name}:")
    lines.append(f'    """Auto-generated model for {entity.name}."""')
    lines.append(f"    {entity.primary_key}: Optional[int] = None")
    for field in entity.fields:
        py_type = _py_type(field.type)
        default = '""' if py_type == "str" else "None"
        lines.append(f"    {field.name}: {py_type} = {default}")
    if entity.timestamps:
        lines.append("    created_at: Optional[str] = None")
        lines.append("    updated_at: Optional[str] = None")

    # to_dict helper
    lines.append("")
    lines.append("    def to_dict(self) -> dict:")
    lines.append("        from dataclasses import asdict")
    lines.append("        return asdict(self)")
    return lines


def _py_type(field_type: str) -> str:
    return {
        "text": "str",
        "email": "str",
        "password": "str",
        "number": "float",
        "select": "str",
    }.get(field_type, "str")


