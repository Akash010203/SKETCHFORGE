def generate_logic_py(spec: AppSpec) -> str:
    lines: list[str] = [
        '"""Business logic and CRUD operations — generated by SketchForge."""',
        "from __future__ import annotations",
        "",
        "import sqlite3",
        "from typing import Optional, List",
        "from .database import connect",
        "from .models import " + ", ".join(e.name for e in spec.entities),
        "",
    ]
    for entity in spec.entities:
        lines.extend(_crud(entity))
        lines.append("")
    return "\n".join(lines)


def _crud(entity: EntitySpec) -> list[str]:
    table = _snake(entity.name)
    pk = entity.primary_key
    field_names = [f.name for f in entity.fields]
    cols = ", ".join(field_names)
    placeholders = ", ".join("?" for _ in field_names)
    setters = ", ".join(f"{n} = ?" for n in field_names)

    return [
        f"# --------------- {entity.name} ---------------",
        "",
        f"def create_{table}(obj: {entity.name}) -> {entity.name}:",
        f'    """Insert a new {entity.name} and return it with the assigned id."""',
        f"    conn = connect()",
        f"    cursor = conn.execute(",
        f'        "INSERT INTO {table} ({cols}) VALUES ({placeholders})",',
        f"        [{', '.join(f'obj.{n}' for n in field_names)}],",
        f"    )",
        f"    conn.commit()",
        f"    obj.{pk} = cursor.lastrowid",
        f"    conn.close()",
        f"    return obj",
        "",
        f"def get_{table}(id: int) -> Optional[{entity.name}]:",
        f'    """Fetch one {entity.name} by primary key."""',
        f"    conn = connect()",
        f"    row = conn.execute('SELECT * FROM {table} WHERE {pk} = ?', (id,)).fetchone()",
        f"    conn.close()",
        f"    if not row: return None",
        f"    return {entity.name}(**dict(row))",
        "",
        f"def list_{table}() -> List[{entity.name}]:",
        f'    """Fetch all {entity.name} records."""',
        f"    conn = connect()",
        f"    rows = conn.execute('SELECT * FROM {table} ORDER BY {pk} DESC').fetchall()",
        f"    conn.close()",
        f"    return [{entity.name}(**dict(r)) for r in rows]",
        "",
        f"def update_{table}(obj: {entity.name}) -> bool:",
        f'    """Update an existing {entity.name}. Returns True if a row was changed."""',
        f"    conn = connect()",
        f"    cursor = conn.execute(",
        f'        "UPDATE {table} SET {setters} WHERE {pk} = ?",',
        f"        [{', '.join(f'obj.{n}' for n in field_names)}, obj.{pk}],",
        f"    )",
        f"    conn.commit()",
        f"    conn.close()",
        f"    return cursor.rowcount > 0",
        "",
        f"def delete_{table}(id: int) -> bool:",
        f'    """Delete a {entity.name} by primary key."""',
        f"    conn = connect()",
        f"    cursor = conn.execute('DELETE FROM {table} WHERE {pk} = ?', (id,))",
        f"    conn.commit()",
        f"    conn.close()",
        f"    return cursor.rowcount > 0",
    ]


