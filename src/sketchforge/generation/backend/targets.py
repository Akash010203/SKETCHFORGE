"""Optional backend target renderers (SQLAlchemy, Prisma, FastAPI, GraphQL, auth)."""
from __future__ import annotations

from sketchforge.generation.app_specification import AppSpec
from sketchforge.generation.backend.schema_generator import _py_type, _snake


def sqlalchemy_models(spec: AppSpec) -> str:
    lines = ['"""SQLAlchemy models generated by SketchForge."""',
             'from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column',
             'from sqlalchemy import String, Float, DateTime, func', '',
             'class Base(DeclarativeBase): pass', '']
    for entity in spec.entities:
        lines += [f'class {entity.name}(Base):', '    __tablename__ = ' + repr(_snake(entity.name)),
                  '    id: Mapped[int] = mapped_column(primary_key=True)']
        for f in entity.fields:
            typ = 'Float' if _py_type(f.type) == 'float' else 'String'
            lines.append(f'    {f.name}: Mapped[ str | float | None ] = mapped_column({typ}, nullable={not f.required!r})')
        if entity.timestamps:
            lines += ['    created_at: Mapped[DateTime] = mapped_column(DateTime, server_default=func.now())',
                      '    updated_at: Mapped[DateTime] = mapped_column(DateTime, server_default=func.now(), onupdate=func.now())']
        lines.append('')
    return '\n'.join(lines)


def prisma_schema(spec: AppSpec) -> str:
    provider = {'sqlite': 'sqlite', 'postgresql': 'postgresql', 'mysql': 'mysql'}[spec.database]
    url = {'sqlite': 'file:./dev.db', 'postgresql': 'env("DATABASE_URL")', 'mysql': 'env("DATABASE_URL")'}[spec.database]
    out = ['generator client {', '  provider = "prisma-client-js"', '}', '',
           'datasource db {', f'  provider = "{provider}"', f'  url = {url}', '}', '']
    types = {'text': 'String', 'email': 'String', 'password': 'String', 'number': 'Float', 'select': 'String'}
    for entity in spec.entities:
        out += [f'model {entity.name} {{', f'  {entity.primary_key} Int @id @default(autoincrement())']
        for f in entity.fields:
            out.append(f'  {f.name} {types.get(f.type, "String")}{"" if f.required else "?"}')
        if entity.timestamps:
            out += ['  created_at DateTime @default(now())', '  updated_at DateTime @updatedAt']
        out += ['}', '']
    return '\n'.join(out)


def api_source(spec: AppSpec) -> str:
    """Generate a compact API entry point for the selected Python API target."""
    if spec.api_target == 'fastapi':
        return '''"""FastAPI REST API; install fastapi and uvicorn."""\nfrom fastapi import FastAPI\nfrom pydantic import BaseModel\n\napp = FastAPI(title="Generated API")\n\n@app.get("/health")\ndef health():\n    return {"status": "ok"}\n'''
    if spec.api_target == 'graphql':
        return '''"""GraphQL API; install strawberry-graphql and uvicorn."""\nimport strawberry\nfrom strawberry.asgi import GraphQL\nfrom fastapi import FastAPI\n\n@strawberry.type\nclass Query:\n    @strawberry.field\n    def health(self) -> str:\n        return "ok"\n\nschema = strawberry.Schema(query=Query)\napp = FastAPI()\napp.add_route("/graphql", GraphQL(schema))\n'''
    return '''"""Flask REST API; generated CRUD routes are added by the app scaffold."""\nfrom flask import Flask, jsonify\napp = Flask(__name__)\n\n@app.get("/health")\ndef health():\n    return jsonify(status="ok")\n'''


def auth_source() -> str:
    """Password hashing and signed JWT helpers; secrets are supplied by environment."""
    return '''"""Authentication primitives. Configure AUTH_SECRET before deployment."""\nimport os\nfrom datetime import datetime, timedelta, timezone\nfrom werkzeug.security import check_password_hash, generate_password_hash\nimport jwt\n\n_SECRET = os.environ.get("AUTH_SECRET")\nif not _SECRET:\n    raise RuntimeError("Set AUTH_SECRET to a random secret before importing auth")\n\ndef hash_password(password: str) -> str:\n    if len(password) < 12:\n        raise ValueError("Password must be at least 12 characters")\n    return generate_password_hash(password, method="scrypt")\n\ndef verify_password(password: str, encoded: str) -> bool:\n    return check_password_hash(encoded, password)\n\ndef issue_token(subject: str, minutes: int = 30) -> str:\n    now = datetime.now(timezone.utc)\n    return jwt.encode({"sub": subject, "iat": now, "exp": now + timedelta(minutes=minutes)}, _SECRET, algorithm="HS256")\n\ndef verify_token(token: str) -> dict:\n    return jwt.decode(token, _SECRET, algorithms=["HS256"])\n\n# OAuth2: register provider callback routes and validate state/PKCE in the API layer.\n'''


